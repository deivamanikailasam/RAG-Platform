#!/usr/bin/env python3
"""The risk register as code (Step 36).

    compliance.py check              validate docs/compliance/risk-register.yaml (CI)
    compliance.py docs [--check]     render the threat model, controls and framework matrix

Checks: ids are unique; every threat has controls that exist; every control has evidence, every
evidence file exists and every named test exists in it; every framework reference is one this
script knows (a typo like "Art 51" fails); every control treats at least one threat.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
REGISTER = ROOT / "docs/compliance/risk-register.yaml"
OUT_THREATS = ROOT / "docs/security/threat-model.md"
OUT_CONTROLS = ROOT / "docs/compliance/controls.md"

STRIDE = ["Spoofing", "Tampering", "Repudiation", "Information disclosure", "Denial of service",
          "Elevation of privilege", "Safety"]  # fmt: skip
NIST = {f"{fn} {n}" for fn, ns in {"GOVERN": ["1.1", "1.2", "1.3", "1.4", "1.5", "1.6", "1.7", "2.1", "2.2", "2.3", "3.1", "3.2",
                                              "4.1", "4.2", "4.3", "5.1", "5.2", "6.1", "6.2"],
                                   "MAP": ["1.1", "1.2", "1.3", "1.4", "1.5", "1.6", "2.1", "2.2", "2.3", "3.1", "3.2", "3.3",
                                           "3.4", "3.5", "4.1", "4.2", "5.1", "5.2"],
                                   "MEASURE": [f"1.{i}" for i in range(1, 4)] + [f"2.{i}" for i in range(1, 14)]
                                              + [f"3.{i}" for i in range(1, 4)] + [f"4.{i}" for i in range(1, 4)],
                                   "MANAGE": ["1.1", "1.2", "1.3", "1.4", "2.1", "2.2", "2.3", "2.4", "3.1", "3.2",
                                              "4.1", "4.2", "4.3"]}.items() for n in ns}  # fmt: skip
ISO = {"A.2.2", "A.2.3", "A.2.4", "A.3.2", "A.3.3", "A.4.2", "A.4.3", "A.4.4", "A.4.5", "A.4.6", "A.5.2", "A.5.3",
       "A.5.4", "A.5.5", "A.6.1.2", "A.6.1.3", "A.6.2.2", "A.6.2.3", "A.6.2.4", "A.6.2.5", "A.6.2.6", "A.6.2.7",
       "A.6.2.8", "A.7.2", "A.7.3", "A.7.4", "A.7.5", "A.7.6", "A.8.2", "A.8.3", "A.8.4", "A.8.5", "A.9.2", "A.9.3",
       "A.9.4", "A.10.2", "A.10.3", "A.10.4"}  # fmt: skip
EU = {f"Art. {n}" for n in (4, 5, 9, 10, 11, 12, 13, 14, 15, 17, 26, 27, 50, 72, 73)}
APP = {f"APP {n}" for n in range(1, 14)}
KNOWN = {"nist": NIST, "iso42001": ISO, "eu_ai_act": EU, "app": APP}
NAMES = {
    "nist": "NIST AI RMF 1.0",
    "iso42001": "ISO/IEC 42001 Annex A",
    "eu_ai_act": "EU AI Act",
    "app": "Australian Privacy Principles",
}


def load() -> dict[str, Any]:
    doc: dict[str, Any] = yaml.safe_load(REGISTER.read_text())
    return doc


def problems(doc: dict[str, Any]) -> list[str]:
    out: list[str] = []
    controls = {c["id"]: c for c in doc["controls"]}
    if len(controls) != len(doc["controls"]):
        out.append("duplicate control ids")
    if len({t["id"] for t in doc["threats"]}) != len(doc["threats"]):
        out.append("duplicate threat ids")
    used = set()
    for t in doc["threats"]:
        if t["category"] not in STRIDE:
            out.append(f"{t['id']}: unknown category {t['category']!r}")
        if not t.get("controls"):
            out.append(f"{t['id']}: no controls")
        for c in t.get("controls", []):
            used.add(c)
            if c not in controls:
                out.append(f"{t['id']}: unknown control {c}")
    for cid, c in controls.items():
        if cid not in used:
            out.append(f"{cid}: treats no threat (remove it or link it)")
        if not c.get("evidence"):
            out.append(f"{cid}: no evidence")
        for ev in c.get("evidence", []):
            path, _, test = ev.partition("::")
            f = ROOT / path
            if not f.exists():
                out.append(f"{cid}: evidence {path} does not exist")
            elif test and not re.search(rf"^(async )?def {re.escape(test)}\b", f.read_text(), re.M):
                out.append(f"{cid}: no test {test} in {path}")
        for fw, refs in (c.get("frameworks") or {}).items():
            if fw not in KNOWN:
                out.append(f"{cid}: unknown framework {fw}")
                continue
            out += [
                f"{cid}: unknown {NAMES[fw]} reference {r!r}" for r in refs if r not in KNOWN[fw]
            ]
    return out


def render(doc: dict[str, Any]) -> dict[Path, str]:
    head = "<!-- Generated by scripts/compliance.py from docs/compliance/risk-register.yaml. Don't edit. -->\n\n"
    t = [head + "# Threat model (STRIDE + safety)\n",
         "| Id | Category | Component | Threat | Controls | Residual |", "|---|---|---|---|---|---|"]  # fmt: skip
    for cat in STRIDE:
        for th in (x for x in doc["threats"] if x["category"] == cat):
            t.append(
                f"| {th['id']} | {cat} | {th['component']} | {th['threat']} | {', '.join(th['controls'])} | {th['residual']} |"
            )
    c = [
        head + "# Controls and evidence\n",
        "| Control | What it does | Steps | Evidence |",
        "|---|---|---|---|",
    ]
    for ctl in doc["controls"]:
        evidence = "<br>".join(f"`{e}`" for e in ctl["evidence"])
        c.append(
            f"| **{ctl['id']}** {ctl['title']} | {ctl['description']} | {', '.join(map(str, ctl.get('steps', [])))} | {evidence} |"
        )
    for fw, name in NAMES.items():
        by_ref: defaultdict[str, list[str]] = defaultdict(list)
        for ctl in doc["controls"]:
            for r in (ctl.get("frameworks") or {}).get(fw, []):
                by_ref[r].append(ctl["id"])
        c += ["", f"## {name}", "", "| Reference | Controls |", "|---|---|"]
        c += [
            f"| {r} | {', '.join(ids)} |"
            for r, ids in sorted(by_ref.items(), key=lambda kv: _natural(kv[0]))
        ]
    return {OUT_THREATS: "\n".join(t) + "\n", OUT_CONTROLS: "\n".join(c) + "\n"}


def _natural(s: str) -> list[Any]:
    return [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", s)]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="compliance.py")
    ap.add_argument("cmd", choices=["check", "docs"])
    ap.add_argument(
        "--check", action="store_true", help="docs: fail if the rendered files are out of date"
    )
    a = ap.parse_args(argv)
    doc = load()
    if a.cmd == "check":
        found = problems(doc)
        for p in found:
            print(f"ERROR: {p}", file=sys.stderr)
        print(
            f"{len(doc['threats'])} threats, {len(doc['controls'])} controls, {len(found)} problem(s)"
        )
        return 1 if found else 0
    stale = []
    for path, text in render(doc).items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    for s in stale:
        print(f"ERROR: {s} is out of date: run `just compliance-docs`", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
