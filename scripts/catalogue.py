#!/usr/bin/env python3
"""The catalogue of every switchable option (Step 38), generated from the registry itself.

    catalogue.py [--check]          write (or check) docs/catalogue.md

Because it is generated, it can't drift from the code: a new component appears here the moment
it is registered, with its settings and defaults, and CI fails if the file is out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from rag_core.registry import describe

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/catalogue.md"
STATUS = {"live": "tested against the real service", "mocked": "tested with a stand-in service",
          "reference": "reference implementation"}  # fmt: skip
SLOTS = {  # the slot in rag.yaml for each kind, and what it is for, in order of the pipeline
    "token_counter": "Counting tokens (Step 30)", "parser": "Reading file formats (Step 31)",
    "normalizer": "Cleaning text (Step 31)", "pii": "Personal data (Step 31)",
    "chunker": "Splitting into chunks (Step 31)", "enricher": "Adding context before embedding (Step 31)",
    "embedder": "Turning text into vectors (Step 31)", "vector_store": "Storing vectors (Step 31)",
    "keyword_index": "Keyword search (Step 31)", "manifest": "Remembering what was ingested (Step 31)",
    "queue": "Ingestion jobs (Step 31)", "query_transformer": "Rewriting questions (Step 32)",
    "retriever": "Finding candidates (Step 32)", "fusion": "Combining result lists (Step 32)",
    "sparse_embedder": "Sparse (word-weight) vectors (extension 02)",
    "reranker": "Re-ordering candidates (Step 32)", "postprocessor": "Filtering and shaping results (Step 32)",
    "compressor": "Compressing the context (extension 02)",
    "context_builder": "Packing the context (Step 33)", "generator": "Writing the answer (Step 33)",
    "memory": "Conversation memory (Step 33)", "cache": "Answer cache (Step 33)",
    "search_cache": "Retrieval-result cache (extension 01)",
    "guard": "Guardrails (Step 34)", "pipeline": "RAG architecture (Step 35)",
    "graph_store": "Knowledge graph (Step 35)", "llm": "Language models (Step 30)",
}  # fmt: skip


def render() -> str:
    rows = describe()
    kinds = sorted(
        {r["kind"] for r in rows}, key=lambda k: (list(SLOTS).index(k) if k in SLOTS else 99, k)
    )
    out = ["<!-- Generated by scripts/catalogue.py from the component registry. Don't edit. -->", "",
           "# Catalogue of switchable components", "",
           f"{len(rows)} components in {len(kinds)} kinds. Switch any of them with one line in rag.yaml: "
           "`<slot>: {use: <name>, <setting>: <value>}`. `rag components --kind <kind>` shows the same.", ""]  # fmt: skip
    for kind in kinds:
        out += [
            f"## {kind}: {SLOTS.get(kind, kind)}",
            "",
            "| Name | What it does | Settings (default) | Tested |",
            "|---|---|---|---|",
        ]
        for r in (r for r in rows if r["kind"] == kind):
            settings = (
                ", ".join(
                    f"`{k}`" + ("" if v[1] == "required" else f" ({_short(v[1])})")
                    for k, v in r["params"].items()
                )
                or "none"
            )
            extra = f" Needs extra: `{', '.join(r['requires'])}`." if r["requires"] else ""
            out.append(
                f"| `{r['name']}` | {r['summary'].replace('|', '/')}{extra} | {settings} | {r['status']} |"
            )
        out.append("")
    out += ["Tested: " + "; ".join(f"**{k}** = {v}" for k, v in STATUS.items()) + "."]
    return "\n".join(out) + "\n"


def _short(v: object) -> str:
    s = repr(v)
    s = s if len(s) <= 28 else s[:25] + "…"
    return s.replace("|", "/").replace("`", "'")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="catalogue.py")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print("ERROR: docs/catalogue.md is out of date: run `just catalogue`", file=sys.stderr)
            return 1
        print("docs/catalogue.md is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
