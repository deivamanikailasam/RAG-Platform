"""Reference exporters (extension 04): our run files in other evaluation tools' formats.

    rag eval-export runs/standard.answers.json --to ragas --out standard.ragas.jsonl

No third-party package is imported: these are plain JSON/YAML files in each tool's documented
input shape, so a team that already uses one of them can score our runs there, side by side with
our own metrics. Status: reference. The shapes follow each tool's documentation; check them
against the version you install.

    ragas      JSONL of single-turn samples: user_input, retrieved_contexts, response, reference
               -> ragas.EvaluationDataset.from_list([...])
    deepeval   JSON list of test cases: input, actual_output, expected_output, retrieval_context
               -> EvaluationDataset().add_test_cases_from_json_file(...)
    promptfoo  a promptfooconfig (YAML) whose tests replay our answers through the `echo` provider
               and grade them with promptfoo's RAG assertions (context-faithfulness, factuality, …)
    trulens    JSON list of virtual records: main_input, main_output, the retriever call's contexts
               -> TruVirtual / VirtualRecord
    phoenix    JSONL of OpenInference spans (a CHAIN span with a RETRIEVER child per case)
               -> a pandas DataFrame -> px.Client().log_traces(TraceDataset(df))
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
from collections.abc import Callable
from typing import Any

import yaml

TARGETS = ("ragas", "deepeval", "promptfoo", "trulens", "phoenix")


def _contexts(case: dict[str, Any]) -> list[str]:
    return [c["text"] for c in case.get("contexts", [])]


def _require_answers(run: dict[str, Any]) -> list[dict[str, Any]]:
    if run.get("suite") != "answers":
        raise ValueError(
            "exporters need an answers run (rag eval-answers --out …), not a search run"
        )
    return list(run["cases"])


def to_ragas(run: dict[str, Any]) -> str:
    rows = []
    for c in _require_answers(run):
        row: dict[str, Any] = {
            "user_input": c["question"],
            "retrieved_contexts": _contexts(c),
            "response": c["answer"],
        }
        if c.get("reference"):
            row["reference"] = c["reference"]
        rows.append(row)
    return "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n"


def to_deepeval(run: dict[str, Any]) -> str:
    cases = [{"input": c["question"], "actual_output": c["answer"], "expected_output": c.get("reference"),
              "retrieval_context": _contexts(c), "name": c["id"],
              "additional_metadata": {"relevant": c.get("relevant", []), "cited": c.get("cited", []),
                                      "rag_core_metrics": c.get("metrics", {})}}
             for c in _require_answers(run)]  # fmt: skip
    return json.dumps(cases, indent=2, ensure_ascii=False) + "\n"


def to_promptfoo(run: dict[str, Any]) -> str:
    tests = []
    for c in _require_answers(run):
        asserts: list[dict[str, Any]] = [{"type": "context-faithfulness", "threshold": 0.7},
                                         {"type": "answer-relevance", "threshold": 0.7}]  # fmt: skip
        if c.get("reference"):
            asserts += [{"type": "factuality", "value": c["reference"]},
                        {"type": "context-recall", "value": c["reference"], "threshold": 0.7}]  # fmt: skip
        tests.append({"description": c["id"],
                      "vars": {"query": c["question"], "context": "\n\n".join(_contexts(c)), "answer": c["answer"]},
                      "assert": asserts})  # fmt: skip
    config = {"description": f"rag-core run {run['variant']} ({run['dataset']})",
              "prompts": ["{{answer}}"], "providers": ["echo"], "tests": tests}  # fmt: skip
    head = (
        "# Generated by `rag eval-export --to promptfoo`: replays stored answers (echo provider).\n"
    )
    return head + yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=120)


def to_trulens(run: dict[str, Any]) -> str:
    records = [{"main_input": c["question"], "main_output": c["answer"],
                "calls": {"retriever": {"args": {"query": c["question"]}, "rets": _contexts(c)}},
                "meta": {"id": c["id"], "variant": run["variant"], "ground_truth": c.get("reference"),
                         "rag_core_metrics": c.get("metrics", {})}}
               for c in _require_answers(run)]  # fmt: skip
    return json.dumps(records, indent=2, ensure_ascii=False) + "\n"


def _hex(seed: str, n: int) -> str:
    return hashlib.sha256(seed.encode()).hexdigest()[:n]


def to_phoenix(run: dict[str, Any]) -> str:
    """OpenInference span rows as Phoenix's spans DataFrame names its columns."""
    start = dt.datetime.fromisoformat(run.get("created_at") or "2026-01-01T00:00:00+00:00")
    rows = []
    for c in _require_answers(run):
        trace_id = _hex(f"{run['variant']}|{c['id']}", 32)
        root, child = _hex(trace_id + "root", 16), _hex(trace_id + "retriever", 16)
        end = start + dt.timedelta(milliseconds=float(c.get("ms") or 0))
        common = {"context.trace_id": trace_id, "start_time": start.isoformat(), "end_time": end.isoformat(),
                  "status_code": "OK"}  # fmt: skip
        rows.append(common | {"context.span_id": root, "parent_id": None, "name": "rag.answer", "span_kind": "CHAIN",
                              "attributes.openinference.span.kind": "CHAIN",
                              "attributes.input.value": c["question"], "attributes.output.value": c["answer"],
                              "attributes.metadata": {"case": c["id"], "variant": run["variant"],
                                                      "reference": c.get("reference"), **c.get("metrics", {})}})  # fmt: skip
        rows.append(common | {"context.span_id": child, "parent_id": root, "name": "rag.search", "span_kind": "RETRIEVER",
                              "attributes.openinference.span.kind": "RETRIEVER",
                              "attributes.input.value": c["question"],
                              "attributes.retrieval.documents": [
                                  {"document.id": x.get("chunk_id", ""), "document.content": x["text"],
                                   "document.metadata": {"document": x.get("document", "")}}
                                  for x in c.get("contexts", [])]})  # fmt: skip
    return "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n"


EXPORTERS: dict[str, Callable[[dict[str, Any]], str]] = {
    "ragas": to_ragas, "deepeval": to_deepeval, "promptfoo": to_promptfoo, "trulens": to_trulens,
    "phoenix": to_phoenix,
}  # fmt: skip
EXTENSIONS = {
    "ragas": "jsonl",
    "deepeval": "json",
    "promptfoo": "yaml",
    "trulens": "json",
    "phoenix": "jsonl",
}


def export(run: dict[str, Any], target: str) -> str:
    if target not in EXPORTERS:
        raise ValueError(f"unknown export target {target!r} (have: {', '.join(TARGETS)})")
    return EXPORTERS[target](run)


__all__ = ["EXPORTERS", "EXTENSIONS", "TARGETS", "export"]
