"""Compare search configurations (Step 32) and RAG architectures (Step 35) on the same questions.

    rag eval-search examples/eval/handbook.yaml --profile offline
    rag eval-search examples/eval/handbook.yaml --profile local --no-ingest --variant hybrid --variant hybrid+rerank

A dataset names its corpus, the person asking, the questions with the documents that answer
them (and documents that must NEVER appear), and variants: small changes to the profile.
Each variant is built fresh, ingests the corpus (unless --no-ingest), answers every question and
gets document-level scores: hit rate@k, recall@k, precision@k, MRR, MAP, nDCG@k (extension 04
added hit rate, precision and MAP), leaks and latency.

    rag eval-answers examples/eval/handbook.yaml --profile offline [--variant standard …]

builds each of the dataset's `architectures` the same way and runs every question through the
whole answer pipeline: context recall, answered, cited, abstained, grounded, leaks and latency;
extension 04 adds faithfulness, answer relevance, context precision, correctness against a
`reference` answer, citation precision/recall (scored by the profile's `judge`, lexical by
default), and a run file (`--out`) with every question, answer and context for A/B tests and
exporters (rag_core/evalkit).

Questions generated by `rag eval-generate` or proposed from feedback carry `review: pending` and
are left out until a person sets `review: approved` (or `--include-unreviewed`).
"""

from __future__ import annotations

import copy
import math
import statistics
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from rag_core import config as cfg
from rag_core.registry import ComponentError, Container
from rag_core.types import Access, Principal, Query, Turn


@dataclass(frozen=True)
class Case:
    id: str
    question: str
    relevant: tuple[str, ...]  # document names (end of the URI) that answer it
    forbidden: tuple[str, ...] = ()  # documents this person must never get
    history: tuple[Turn, ...] = ()
    tags: tuple[str, ...] = ()
    reference: str | None = None  # extension 04: a reference answer, for correctness


@dataclass
class Scores:
    variant: str
    recall: float
    mrr: float
    ndcg: float
    leaks: int
    p50_ms: float
    per_case: dict[str, dict[str, Any]] = field(default_factory=dict)
    hit_rate: float = 0.0  # extension 04
    precision: float = 0.0
    map: float = 0.0

    def row(self) -> dict[str, Any]:
        return {"variant": self.variant, "hit_rate": self.hit_rate, "recall": self.recall,
                "precision": self.precision, "mrr": self.mrr, "map": self.map, "ndcg": self.ndcg,
                "leaks": self.leaks, "p50_ms": self.p50_ms}  # fmt: skip


def doc_name(uri: str) -> str:
    return uri.rstrip("/").rsplit("/", 1)[-1]


def metrics(ranked_docs: list[str], relevant: set[str], k: int) -> tuple[float, float, float]:
    """Document-level recall@k, reciprocal rank and nDCG@k (binary relevance)."""
    top = ranked_docs[:k]
    found = [d for d in top if d in relevant]
    recall = len(set(found)) / len(relevant)
    rr = next((1.0 / i for i, d in enumerate(ranked_docs, 1) if d in relevant), 0.0)
    dcg = sum(1.0 / math.log2(i + 1) for i, d in enumerate(top, 1) if d in relevant)
    idcg = sum(1.0 / math.log2(i + 1) for i in range(1, min(len(relevant), k) + 1))
    return recall, rr, dcg / idcg


UNREVIEWED = ("pending", "rejected")  # extension 04: generated or proposed, not yet approved


def reviewed_only(
    doc: dict[str, Any], include_unreviewed: bool = False
) -> tuple[dict[str, Any], int]:
    """The dataset without questions still waiting for (or refused by) a reviewer; how many."""
    qs = doc.get("questions") or []
    keep = [q for q in qs if (include_unreviewed and q.get("review") != "rejected")
            or q.get("review") not in UNREVIEWED]  # fmt: skip
    return {**doc, "questions": keep}, len(qs) - len(keep)


def load_dataset(path: Path) -> dict[str, Any]:
    try:
        doc = yaml.safe_load(path.read_text())
    except (OSError, yaml.YAMLError) as e:
        raise ComponentError(f"{path}: {e}") from None
    if not isinstance(doc, dict) or doc.get("version") != 1:
        raise ComponentError(f"{path}: expected 'version: 1'")
    return doc


def _cases(doc: dict[str, Any]) -> list[Case]:
    out = []
    for q in doc["questions"]:
        hist = tuple(Turn(t["role"], t["text"]) for t in q.get("history", []))
        out.append(Case(str(q["id"]), q["question"], tuple(q.get("relevant", [])),
                        tuple(q.get("forbidden", [])), hist, tuple(q.get("tags", [])),
                        q.get("reference")))  # fmt: skip
    return out


def ingest_corpus(container: Container, doc: dict[str, Any], base: Path) -> int:
    """Ingest a dataset's corpus with its real access rules (used by eval-search, `rag ask --corpus`
    and the answer tests, Step 33)."""
    from rag_core.ingest import IngestionPipeline, load_source

    pipe = IngestionPipeline(container)
    n = 0
    for item in doc.get("corpus", []):
        acc = item.get("access", {})
        access = Access(acc.get("classification", "internal"), tuple(acc.get("groups", ())),
                        acc.get("tenant", "default"))  # fmt: skip
        uri = item["uri"] if "://" in item["uri"] else f"file://{(base / item['uri']).resolve()}"
        r = pipe.ingest(load_source(uri, access, item.get("metadata", {})))
        if r.status == "failed":
            raise ComponentError(f"corpus file failed to ingest: {uri}: {r.detail}")
        n += r.chunks
    return n


def run_variant(name: str, config: dict[str, Any], doc: dict[str, Any], base: Path,
                ingest: bool = True) -> Scores:  # fmt: skip
    from rag_core.search import SearchPipeline

    container = Container(config, name)
    if ingest:
        ingest_corpus(container, doc, base)
    pipeline = SearchPipeline(container)
    p = doc.get("principal", {})
    who = Principal(p.get("subject", "eval"), tuple(p.get("groups", ())),
                    tuple(p.get("classifications", ("public", "internal"))), p.get("tenant", "default"))  # fmt: skip
    from rag_core.evalkit import metrics as em

    k = int(doc.get("k", 5))
    recalls: list[float] = []
    rrs: list[float] = []
    ndcgs: list[float] = []
    hits: list[float] = []
    precs: list[float] = []
    aps: list[float] = []
    times: list[float] = []
    leaks = 0
    per_case: dict[str, dict[str, Any]] = {}
    for case in _cases(doc):
        t0 = time.perf_counter()
        result = pipeline.search(Query(case.question, who, history=case.history, k=k))
        times.append((time.perf_counter() - t0) * 1000)
        ranked = list(dict.fromkeys(doc_name(h.chunk.document_uri) for h in result.hits))
        bad = [d for d in ranked if d in case.forbidden]
        leaks += len(bad)
        entry: dict[str, Any] = {"docs": ranked, "leaks": bad}
        if case.relevant:
            r, rr, nd = metrics(ranked, set(case.relevant), k)
            recalls.append(r)
            rrs.append(rr)
            ndcgs.append(nd)
            more = em.retrieval_scores(ranked, set(case.relevant), k)
            hits.append(more["hit_rate"])
            precs.append(more["precision"])
            aps.append(more["map"])
            entry |= {"recall": round(r, 3), "rr": round(rr, 3), "ndcg": round(nd, 3),
                      "hit_rate": more["hit_rate"], "precision": round(more["precision"], 3),
                      "ap": round(more["map"], 3)}  # fmt: skip
        per_case[case.id] = entry

    def avg(xs: list[float]) -> float:
        return round(statistics.fmean(xs), 3) if xs else 0.0

    return Scores(name, avg(recalls), avg(rrs), avg(ndcgs), leaks,
                  round(statistics.median(times), 1) if times else 0.0, per_case,
                  avg(hits), avg(precs), avg(aps))  # fmt: skip


def variant_configs(rag_yaml: Path, profile: str, doc: dict[str, Any], only: list[str] | None = None,
                    key: str = "variants") -> dict[str, dict[str, Any]]:  # fmt: skip
    """The profile, with each variant's changes merged on top (same rules as `extends`).
    `key` picks the dataset's section: "variants" (search) or "architectures" (Step 35)."""
    try:
        base_doc = cfg.read(rag_yaml)  # with the platform profiles it includes (Step 38)
    except (OSError, yaml.YAMLError) as e:
        raise ComponentError(f"{rag_yaml}: {e}") from None
    variants = doc.get(key) or {"as-configured": {}}
    unknown = set(only or []) - set(variants)
    if unknown:
        raise ComponentError(f"unknown variant(s) {sorted(unknown)} (have: {', '.join(variants)})")
    out = {}
    for name, changes in variants.items():
        if only and name not in only:
            continue
        d = copy.deepcopy(base_doc)
        d["profiles"]["__variant__"] = {"extends": profile, **(changes or {})}
        out[name] = cfg.resolve(d, "__variant__")
    return out


def format_table(rows: list[Scores], k: int) -> str:
    head = (f"{'variant':34} {'hit@' + str(k):>6} {'recall@' + str(k):>9} {'P@' + str(k):>6} {'MRR':>6} "
            f"{'MAP':>6} {'nDCG@' + str(k):>8} {'leaks':>6} {'p50 ms':>7}")  # fmt: skip
    lines = [head, "-" * len(head)]
    for s in rows:
        lines.append(
            f"{s.variant:34} {s.hit_rate:6.3f} {s.recall:9.3f} {s.precision:6.3f} {s.mrr:6.3f} "
            f"{s.map:6.3f} {s.ndcg:8.3f} {s.leaks:6d} {s.p50_ms:7.1f}"
        )
    return "\n".join(lines)


# ================================================================ answers and architectures (Step 35)


@dataclass
class AnswerScores:
    variant: str
    context_recall: (
        float  # share of the right documents that reached the model (what architectures change)
    )
    answered: float  # answerable questions that got an answer (not "I don't know", not blocked)
    cite_hit: float  # answerable questions whose answer cites a right document
    abstain_ok: float  # unanswerable questions (no relevant document) answered "I don't know"
    grounded: float  # answers the groundedness guard didn't flag
    leaks: int  # forbidden documents cited
    p50_ms: float
    per_case: dict[str, dict[str, Any]] = field(default_factory=dict)
    # extension 04: judged answer metrics (None = nothing to measure, e.g. no reference answers)
    faithfulness: float | None = None
    relevance: float | None = None
    context_precision: float | None = None
    correctness: float | None = None
    citation_precision: float | None = None
    citation_recall: float | None = None
    judge: str = "lexical"
    judge_errors: int = 0
    records: list[dict[str, Any]] = field(default_factory=list)  # the run file's cases

    def row(self) -> dict[str, Any]:
        return {"variant": self.variant, "context_recall": self.context_recall, "answered": self.answered, "cite_hit": self.cite_hit,
                "abstain_ok": self.abstain_ok, "grounded": self.grounded, "faithfulness": self.faithfulness,
                "relevance": self.relevance, "context_precision": self.context_precision,
                "correctness": self.correctness, "citation_precision": self.citation_precision,
                "citation_recall": self.citation_recall, "leaks": self.leaks, "p50_ms": self.p50_ms}  # fmt: skip


def _keep_context(store: dict[str, Any]) -> Any:
    """A before_generation hook that remembers the context the model is about to be shown."""

    def hook(context: Any, early: Any) -> None:
        store["ctx"] = context

    return hook


def run_answers(
    name: str, config: dict[str, Any], doc: dict[str, Any], base: Path, ingest: bool = True
) -> AnswerScores:
    """Every question through the answer pipeline as the dataset's person. Offline these numbers
    describe the plumbing (extractive answers); with --profile local they describe your models."""
    from rag_core.answer import AnswerPipeline
    from rag_core.components.judges import LexicalJudge, LexicalParams
    from rag_core.evalkit import metrics as em

    container = Container(config, name)
    if ingest:
        ingest_corpus(container, doc, base)
    pipe = AnswerPipeline(container)
    judge = container.get("judge") if container.has("judge") else LexicalJudge(LexicalParams())
    p = doc.get("principal", {})
    who = Principal(p.get("subject", "eval"), tuple(p.get("groups", ())),
                    tuple(p.get("classifications", ("public", "internal"))), p.get("tenant", "default"))  # fmt: skip
    answerable = answered = cite_hit = unanswerable = abstain_ok = grounded = leaks = 0
    recalls: list[float] = []
    times: list[float] = []
    per_case: dict[str, dict[str, Any]] = {}
    judged: dict[str, list[float | None]] = {k: [] for k in (
        "faithfulness", "relevance", "context_precision", "correctness", "citation_precision", "citation_recall")}  # fmt: skip
    records: list[dict[str, Any]] = []
    judge_errors = 0
    for case in _cases(doc):
        session = None
        if case.history and pipe.memory is not None:
            session = f"eval-{name}-{case.id}"
            pipe.memory.append(who, session, *case.history)
        seen: dict[str, Any] = {}
        t0 = time.perf_counter()
        a = pipe.answer(case.question, who, session_id=session,
                        before_generation=_keep_context(seen))  # fmt: skip
        ms = (time.perf_counter() - t0) * 1000
        times.append(ms)
        cited = {doc_name(c.document_uri) for c in a.citations}
        bad = sorted(cited & set(case.forbidden))
        leaks += len(bad)
        flagged = any(g["guard"] == "groundedness" for g in a.trace.get("guards", []))
        refused = a.abstained or bool(a.blocked)
        in_context = {doc_name(u) for u in a.trace.get("context", {}).get("documents", [])}
        relevant = set(case.relevant)
        if case.relevant:
            answerable += 1
            recalls.append(len(in_context & relevant) / len(relevant))
            answered += 0 if refused else 1
            cite_hit += 1 if cited & relevant else 0
            grounded += 1 if not refused and not flagged else 0
        else:
            unanswerable += 1
            abstain_ok += 1 if refused else 0
        # extension 04: the judged metrics, from what the model was actually shown
        ctx = seen.get("ctx")
        chunks = list(ctx.chunks) if ctx is not None else []
        contexts = [h.chunk.text for h in chunks]
        ctx_docs = [doc_name(h.chunk.document_uri) for h in chunks]
        scores: dict[str, float | None] = {}
        if not refused:
            js = judge.score(case.question, a.text, contexts, case.reference)
            judge_errors += int(bool(js.pop("judge_error", 0)))
            scores |= {"faithfulness": js.get("faithfulness"), "relevance": js.get("answer_relevance"),
                       "correctness": js.get("correctness")}  # fmt: skip
            scores["citation_precision"] = em.citation_precision(cited, relevant)
            scores["citation_recall"] = em.citation_recall(cited, relevant)
        elif case.reference and case.relevant:
            scores["correctness"] = 0.0  # it should have answered
        scores["context_precision"] = em.context_precision(ctx_docs, relevant)
        for key, vals in judged.items():
            vals.append(scores.get(key))
        search = a.trace.get("search")
        per_case[case.id] = {"cited": sorted(cited), "abstained": a.abstained, "blocked": bool(a.blocked),
                             "flagged": flagged, "leaks": bad,
                             "route": search.get("route") if isinstance(search, dict) else None}  # fmt: skip
        records.append({
            "id": case.id, "question": case.question, "reference": case.reference,
            "relevant": list(case.relevant), "forbidden": list(case.forbidden), "tags": list(case.tags),
            "history": [{"role": t.role, "text": t.text} for t in case.history],
            "answer": a.text, "abstained": a.abstained, "blocked": bool(a.blocked), "cited": sorted(cited),
            "contexts": [{"document": d, "chunk_id": h.chunk.id, "text": h.chunk.text}
                         for d, h in zip(ctx_docs, chunks, strict=True)],
            "metrics": {k: (round(v, 4) if isinstance(v, float) else v) for k, v in scores.items()}
                       | {"context_recall": round(len(in_context & relevant) / len(relevant), 4) if relevant else None,
                          "abstention_correct": em.abstention_correct(refused, bool(case.relevant))},
            "ms": round(ms, 1),
        })  # fmt: skip

    def rate(n: int, d: int) -> float:
        return round(n / d, 3) if d else 1.0

    return AnswerScores(name, round(statistics.fmean(recalls), 3) if recalls else 1.0, rate(answered, answerable),
                        rate(cite_hit, answerable), rate(abstain_ok, unanswerable), rate(grounded, answered or 1),
                        leaks, round(statistics.median(times), 1) if times else 0.0, per_case,
                        em.mean(judged["faithfulness"]), em.mean(judged["relevance"]),
                        em.mean(judged["context_precision"]), em.mean(judged["correctness"]),
                        em.mean(judged["citation_precision"]), em.mean(judged["citation_recall"]),
                        getattr(judge, "name", type(judge).__name__), judge_errors, records)  # fmt: skip


def _cell(v: float | None, width: int) -> str:
    return f"{v:{width}.3f}" if v is not None else f"{'-':>{width}}"


def format_answer_table(rows: list[AnswerScores]) -> str:
    head = (f"{'architecture':22} {'ctx recall':>10} {'answered':>9} {'cite hit':>9} {'abstain ok':>11} "
            f"{'grounded':>9} {'faithful':>9} {'relevant':>9} {'ctx prec':>9} {'correct':>8} "
            f"{'cite P':>7} {'cite R':>7} {'leaks':>6} {'p50 ms':>7}")  # fmt: skip
    lines = [head, "-" * len(head)]
    for s in rows:
        lines.append(
            f"{s.variant:22} {s.context_recall:10.3f} {s.answered:9.3f} {s.cite_hit:9.3f} "
            f"{s.abstain_ok:11.3f} {s.grounded:9.3f} {_cell(s.faithfulness, 9)} {_cell(s.relevance, 9)} "
            f"{_cell(s.context_precision, 9)} {_cell(s.correctness, 8)} {_cell(s.citation_precision, 7)} "
            f"{_cell(s.citation_recall, 7)} {s.leaks:6d} {s.p50_ms:7.1f}"
        )
    return "\n".join(lines)


# ================================================================ guardrails (Step 34)


@dataclass
class GuardScores:
    cases: int
    attacks: int
    caught: int  # attacks the guards stopped, redacted or flagged
    benign: int
    false_positives: int  # benign cases the guards did NOT allow
    wrong: list[dict[str, Any]] = field(default_factory=list)
    known_gaps: list[dict[str, Any]] = field(
        default_factory=list
    )  # attacks we KNOW these guards miss

    @property
    def catch_rate(self) -> float:
        return round(self.caught / self.attacks, 3) if self.attacks else 1.0

    @property
    def false_positive_rate(self) -> float:
        return round(self.false_positives / self.benign, 3) if self.benign else 0.0

    def row(self) -> dict[str, Any]:
        return {"cases": self.cases, "attacks": self.attacks, "caught": self.caught,
                "catch_rate": self.catch_rate, "benign": self.benign,
                "false_positives": self.false_positives, "false_positive_rate": self.false_positive_rate,
                "wrong": self.wrong, "known_gaps": self.known_gaps}  # fmt: skip


def eval_guards(container: Container, doc: dict[str, Any]) -> GuardScores:
    """Run every case through the configured guards of its stage. `expect` is what at least one
    guard must do: block, redact, flag, or allow (= no guard may object)."""
    from dataclasses import replace

    from rag_core.components.generation import is_abstention
    from rag_core.components.guards import GeneratedAnswer
    from rag_core.types import Access, Answer, Chunk, ScoredChunk

    guards = container.get("guards") if container.has("guards") else []
    who = Principal("eval", ("all-staff",), ("public", "internal"))
    s = GuardScores(0, 0, 0, 0, 0)
    for case in doc["cases"]:
        stage, expect = case["stage"], case["expect"]
        sources = tuple(ScoredChunk(Chunk(f"s{i}", f"doc://source-{i}", i, t, len(t.split()), Access("public")), 1.0)
                        for i, t in enumerate(case.get("sources", [])))  # fmt: skip
        if stage == "output":
            payload: Any = GeneratedAnswer(
                Answer(case["text"], abstained=is_abstention(case["text"])), sources
            )
        elif stage == "context":
            payload = list(sources)
        else:
            payload = case["text"]
        actions = []
        for g in guards:
            if g.stage == stage:
                v = g.check(Query(case.get("question", case.get("text", "")), who), payload)
                if v.action != "allow":
                    actions.append(v.action)
                    if v.action == "redact" and v.replacement is not None:
                        # as in the pipeline: a corrected Answer keeps its sources
                        if isinstance(payload, GeneratedAnswer) and isinstance(
                            v.replacement, Answer
                        ):
                            payload = replace(payload, answer=v.replacement)
                        else:
                            payload = v.replacement
        if case.get("known_gap"):  # documented weakness: reported, not scored
            s.known_gaps.append({"id": case["id"], "caught": bool(actions)})
            continue
        s.cases += 1
        if expect == "allow":
            s.benign += 1
            ok = not actions
            s.false_positives += 0 if ok else 1
        else:
            s.attacks += 1
            ok = expect in actions
            s.caught += 1 if actions else 0
        if not ok:
            s.wrong.append(
                {"id": case["id"], "stage": stage, "expected": expect, "got": actions or ["allow"]}
            )
    return s


def format_guard_scores(s: GuardScores) -> str:
    lines = [
        f"{s.cases} cases: {s.attacks} attacks, {s.benign} benign",
        f"{'caught':20} {f'{s.caught}/{s.attacks}':12} catch rate {s.catch_rate:.3f}",
        f"{'false alarms ' + f'{s.false_positives}/{s.benign}':33} false positive rate {s.false_positive_rate:.3f}",
    ]  # fmt: skip
    for w in s.wrong:
        lines.append(f"   wrong {w['id']:34} expected {w['expected']}, got {', '.join(w['got'])}")
    for g in s.known_gaps:
        status = "now CAUGHT" if g["caught"] else "still missed (needs a model-based guard)"
        lines.append(f"   known gap {g['id']:38} {status}")
    return "\n".join(lines)
